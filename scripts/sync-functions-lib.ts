/**
 * The Edge Functions validate, publish and sanitise with the same code as the site and Studio
 * (06 · JSON documents, 10 · Code architecture: one definition of every data shape). Deno needs
 * explicit `.ts` import paths and can't reach outside `supabase/functions`, so this copies the
 * shared modules from `src/lib` into `supabase/functions/_shared/lib/`, rewriting only the imports.
 *
 *   node scripts/sync-functions-lib.ts           write the copies
 *   node scripts/sync-functions-lib.ts --check   fail if a copy is out of date (a unit test runs this)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

export const SHARED_MODULES = ["schemas", "types", "published", "rich-text", "links"] as const;
export const SOURCE_DIR = "src/lib";
export const TARGET_DIR = "supabase/functions/_shared/lib";

const HEADER =
  "// Generated by scripts/sync-functions-lib.ts from src/lib. Don't edit: change src/lib and run the script.\n";

/** The Deno copy of one module: relative imports get their `.ts` extension. */
export function denoCopy(source: string): string {
  const rewritten = source.replace(
    /(from\s+["'])(\.{1,2}\/[^"']+?)(["'])/g,
    (whole, start: string, path: string, end: string) =>
      path.endsWith(".ts") ? whole : `${start}${path}.ts${end}`,
  );
  return HEADER + rewritten;
}

/** Modules whose copy is missing or differs from what the script would write. */
export function staleCopies(root = "."): string[] {
  return SHARED_MODULES.filter((name) => {
    const target = join(root, TARGET_DIR, `${name}.ts`);
    const want = denoCopy(readFileSync(join(root, SOURCE_DIR, `${name}.ts`), "utf8"));
    return !existsSync(target) || readFileSync(target, "utf8") !== want;
  });
}

export function writeCopies(root = "."): void {
  mkdirSync(join(root, TARGET_DIR), { recursive: true });
  for (const name of SHARED_MODULES) {
    const source = readFileSync(join(root, SOURCE_DIR, `${name}.ts`), "utf8");
    // Every import of a shared module must point at another shared module (or zod).
    for (const m of source.matchAll(/from\s+["'](\.{1,2}\/[^"']+)["']/g)) {
      const dep = (m[1] ?? "").replace(/^\.\//, "").replace(/\.ts$/, "");
      if (!(SHARED_MODULES as readonly string[]).includes(dep)) {
        throw new Error(`src/lib/${name}.ts imports ${m[1] ?? ""}, which isn't shared with the functions.`);
      }
    }
    writeFileSync(join(root, TARGET_DIR, `${name}.ts`), denoCopy(source));
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  if (process.argv.includes("--check")) {
    const stale = staleCopies();
    if (stale.length > 0) {
      console.error(
        `Out of date in ${TARGET_DIR}: ${stale.join(", ")}. Run node scripts/sync-functions-lib.ts.`,
      );
      process.exit(1);
    }
    console.log("Function copies of src/lib are up to date.");
  } else {
    writeCopies();
    console.log(`Wrote ${SHARED_MODULES.length} modules to ${TARGET_DIR}.`);
  }
}
